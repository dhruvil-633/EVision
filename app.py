"""EVision - Intelligent EV Energy Management.

Streamlit entry point. Business logic lives in config/, data/, simulation/,
algorithms/ and evaluation/; this file only wires the UI together.

Run with:  streamlit run app.py
"""

from __future__ import annotations

import streamlit as st

st.set_page_config(page_title="EVision - Intelligent EV Energy Management",
                   page_icon="⚡", layout="wide",
                   initial_sidebar_state="expanded")

from ui import (algorithm_page, comparison_page, dashboard, explainability_page,  # noqa: E402
                fleet_page, report_page, simulation_page, state, theme)

PAGES = {
    "Executive Dashboard": dashboard.render,
    "EV Fleet": fleet_page.render,
    "Energy Simulation": simulation_page.render,
    "Algorithm Laboratory": algorithm_page.render,
    "Performance Comparison": comparison_page.render,
    "Soft Computing Explainability": explainability_page.render,
    "Research Report": report_page.render,
}


def sidebar():
    cfg = state.cfg()
    with st.sidebar:
        st.markdown("## ⚡ EVision")
        st.caption("Intelligent EV charging and energy optimization")
        st.markdown("---")
        page = st.radio("Navigate", list(PAGES), label_visibility="collapsed")
        st.markdown("---")
        st.markdown("### Scenario")
        with st.form("scenario_form", border=False):
            seed = st.number_input("Random seed", 0, 10_000, cfg.seed, 1,
                                   help="Fixing the seed makes the whole "
                                        "simulation reproducible.")
            n_evs = st.slider("Fleet size (EVs)", 0, 120, cfg.n_evs, 1)
            station = st.slider("Station capacity (kW)", 20, 500,
                                int(cfg.station_capacity_kw), 10,
                                help="Hard shared power limit of the site.")
            solar = st.slider("Solar capacity (kW)", 0, 400,
                              int(cfg.solar_capacity_kw), 10)
            eff = st.slider("Charging efficiency", 0.80, 1.00,
                            float(cfg.charging_efficiency), 0.01)
            clouds = st.slider("Cloud variability", 0.0, 0.6,
                               float(cfg.cloud_variability), 0.02,
                               help="0 = perfectly clear deterministic sky.")
            applied = st.form_submit_button("Apply and regenerate",
                                            use_container_width=True, type="primary")
        if applied:
            state.apply_config(cfg.with_(seed=int(seed), n_evs=int(n_evs),
                                         station_capacity_kw=float(station),
                                         solar_capacity_kw=float(solar),
                                         charging_efficiency=float(eff),
                                         cloud_variability=float(clouds)))
            st.rerun()

        st.markdown("---")
        st.caption("Synthetic-data simulation. Solar, tariffs and EV sessions "
                   "are generated by mathematical models with a seeded RNG - "
                   "not measured data.")
    return page


def main():
    theme.inject_css()
    theme.register_template()
    state.init()
    page = sidebar()
    PAGES[page]()


main()
