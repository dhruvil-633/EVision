"""Page 7 - Research report and data exports."""

from __future__ import annotations

import streamlit as st

from evaluation.comparison import STRATEGIES, summary_table
from evaluation.report_generator import (DISCLAIMER, build_report,
                                         fleet_result_frame, schedule_frame)
from ui import state, theme

OUTLINE = """
1. **Introduction** - electrification, charging infrastructure, the scheduling problem.
2. **Literature review** - fuzzy logic, evolutionary computation and hybrid
   soft computing methods applied to EV charging and demand-side management.
3. **Problem formulation** - time discretisation, decision variables, hard
   constraints and the weighted multi-objective function.
4. **Methodology** - synthetic scenario generation, Mamdani fuzzy controller,
   genetic algorithm, feasible schedule decoding, hybrid coupling.
5. **Experimental setup** - configuration, seeds, baselines, metric definitions.
6. **Results and discussion** - cost, peak, solar utilisation, deadline
   compliance, convergence behaviour, sensitivity to the objective weights.
7. **Limitations and threats to validity** - synthetic data, perfect foresight,
   constant efficiency, stochastic heuristics.
8. **Conclusion and future scope** - V2G, stochastic arrivals, real tariffs and
   measured irradiance, multi-station coordination.
"""

ABSTRACT = """
This work presents EVision, a simulation platform for intelligent charging of
an electric-vehicle fleet at a shared, solar-equipped charging station. The
scheduling problem is formulated over a 24-hour horizon discretised into
15-minute slots, subject to hard constraints on charger ratings, shared station
capacity, vehicle availability and battery capacity. A Mamdani fuzzy inference
system maps four normalised indicators - deadline urgency, time-of-use price,
on-site solar availability and remaining grid headroom - onto a charging
priority for every vehicle and slot. These priorities seed and steer a genetic
algorithm that evolves a feasible charging schedule against a weighted
objective combining electricity cost, peak grid demand, unmet requested energy,
charging delay and a solar self-consumption reward. The hybrid is compared with
uncontrolled charging, a crisp rule-based heuristic and a plain genetic
algorithm on identical synthetic scenarios. All inputs are generated by
configurable mathematical models with a fixed random seed, so every experiment
is reproducible; no trained model, external data set or physical hardware is
required.
"""


def render():
    theme.hero("Research Report",
               "Generated from the simulation that is currently loaded")
    sc = state.scenario()
    if sc.fleet.n_evs == 0:
        theme.note("Generate a fleet and run a simulation to produce a report.")
        return

    results = state.ensure()
    report = build_report(sc, results)

    c = st.columns(3)
    with c[0]:
        st.download_button("Download report (Markdown)", report.encode(),
                           file_name="evision_report.md", mime="text/markdown",
                           use_container_width=True, type="primary")
    with c[1]:
        st.download_button("Download comparison CSV",
                           summary_table(results, sc).to_csv().encode(),
                           file_name="evision_comparison.csv", mime="text/csv",
                           use_container_width=True)
    with c[2]:
        strategy = st.selectbox("Export schedule of", STRATEGIES,
                                index=STRATEGIES.index(st.session_state.active),
                                label_visibility="collapsed")

    c = st.columns(3)
    with c[0]:
        st.download_button("Download EV data CSV",
                           fleet_result_frame(results[strategy], sc)
                           .to_csv(index=False).encode(),
                           file_name="evision_fleet.csv", mime="text/csv",
                           use_container_width=True)
    with c[1]:
        st.download_button("Download charging schedule CSV",
                           schedule_frame(results[strategy], sc)
                           .to_csv(index=False).encode(),
                           file_name="evision_schedule.csv", mime="text/csv",
                           use_container_width=True)
    with c[2]:
        st.download_button("Download slot-level energy CSV",
                           results[strategy].slot_frame(sc).to_csv(index=False).encode(),
                           file_name="evision_slots.csv", mime="text/csv",
                           use_container_width=True)

    tab_r, tab_a, tab_o = st.tabs(["Results summary", "Abstract", "Report outline"])
    with tab_r:
        st.markdown(report)
    with tab_a:
        st.markdown("#### Abstract")
        st.markdown(ABSTRACT)
        theme.note(DISCLAIMER)
    with tab_o:
        st.markdown("#### Suggested project report outline")
        st.markdown(OUTLINE)
